import assert from 'node:assert/strict';
import {chromeLaunchOptions} from '../../src/readers/browser_launch.mjs';
const options={headless:false,env:{PAPERTRAIL_EXAMPLE_FLAG:'kept'}};
const selected=chromeLaunchOptions(options);
assert.equal(selected.channel,'chrome');
assert.equal(selected.headless,false);
assert.equal(selected.env.PAPERTRAIL_EXAMPLE_FLAG,'kept');
assert.equal(options.channel,undefined,'Caller options are not mutated');
assert.equal(chromeLaunchOptions({channel:'chromium'}).channel,'chrome','Every route uses Google Chrome');
console.log('All portal launches select installed Google Chrome.');
