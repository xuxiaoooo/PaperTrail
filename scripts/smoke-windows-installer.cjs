'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {execFileSync}=require('node:child_process');
const {_electron}=require('playwright-core');
const brand=require('../src/desktop/brand.cjs');
assert.equal(process.platform,'win32','Run this check on Windows');
const root=path.resolve(__dirname,'..'),version=require('../package.json').version.replace(/\.0$/,'');
const output=path.join(root,'build/test-results');fs.mkdirSync(output,{recursive:true});
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'papertrail-installer-'));
const install=path.join(temporary,'PaperTrail'),data=path.join(temporary,'data');
const runtime=path.join(install,'resources/runtime');
const installer=path.join(root,'build/work/windows-x64',`${brand.englishName}-${version}-Windows.exe`);
const env={...process.env,HTTP_PROXY:'http://127.0.0.1:9',HTTPS_PROXY:'http://127.0.0.1:9',ALL_PROXY:'http://127.0.0.1:9',NO_PROXY:'localhost,127.0.0.1',PAPERTRAIL_TEST_DATA_DIR:data};
const report={version,checks:[],errors:[]};
let app;
const launch=()=>_electron.launch({executablePath:path.join(install,brand.englishName+'.exe'),args:[],env,timeout:60000});
(async()=>{
 const started=Date.now();
 execFileSync(installer,['/S',`/D=${install}`],{env,timeout:300000,stdio:'inherit'});
 assert.ok(fs.existsSync(path.join(install,brand.englishName+'.exe')));
 assert.ok(!fs.existsSync(path.join(runtime,'browsers')));
 report.installSeconds=Math.round((Date.now()-started)/1000);
 report.checks.push('Silent NSIS installation completes without downloading browsers');
 execFileSync(path.join(install,brand.englishName+'.exe'),[path.join(root,'scripts/smoke-browsers.cjs')],{env:{...env,ELECTRON_RUN_AS_NODE:'1',PAPERTRAIL_TEST_RUNTIME:runtime},timeout:90000,stdio:'inherit'});
 report.checks.push('Installed Google Chrome launches and renders local content');
 app=await launch();let page=await app.firstWindow();
 page.on('pageerror',error=>report.errors.push(error.message));
 await page.getByRole('heading',{name:'投稿状态'}).waitFor({timeout:30000});
 assert.ok(page.url().startsWith('papertrail://app/'));
 assert.equal((await page.evaluate(()=>window.papertrail.info())).version,version);
 await page.screenshot({path:path.join(output,'windows-welcome.png')});
 await page.getByRole('button',{name:'添加期刊账号'}).first().waitFor();
 assert.equal(fs.existsSync(path.join(data,'components')),false,'First launch must not create a browser download cache');
 report.checks.push('Fresh profile reaches the dashboard using system Google Chrome');
 await page.screenshot({path:path.join(output,'windows-overview.png')});
 await app.close();app=null;
 app=await launch();page=await app.firstWindow();
 await page.getByRole('heading',{name:'投稿状态'}).waitFor({timeout:30000});
 assert.equal(await page.getByRole('heading',{name:'欢迎使用 PaperTrail'}).count(),0);
 assert.equal(fs.existsSync(path.join(data,'components')),false);
 report.checks.push('Relaunch uses system Google Chrome');
 assert.deepEqual(report.errors,[]);
 await app.close();app=null;
 report.ok=true;
})().catch(error=>{report.ok=false;report.error=error.stack;console.error(error);process.exitCode=1;}).finally(async()=>{
 if(app)await app.close().catch(()=>{});
 fs.writeFileSync(path.join(output,'installer-windows.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
});
