const {_electron}=require('playwright-core');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const {componentsReady}=require('../src/desktop/browser-components.cjs');
const root=path.resolve(__dirname,'..'),target=process.platform==='darwin'?'macos-arm64':'windows-x64';
const data=fs.mkdtempSync(path.join(os.tmpdir(),'papertrail-first-launch-'));
const brand=require('../src/desktop/brand.cjs');
const executable=process.env.PAPERTRAIL_TEST_EXECUTABLE||path.join(root,'build/work',target+'-offline',process.platform==='darwin'?'mac-arm64/'+brand.englishName+'.app/Contents/MacOS/'+brand.englishName:'win-unpacked/'+brand.englishName+'.exe');
const resources=process.platform==='darwin'?path.resolve(executable,'../../Resources'):path.join(path.dirname(executable),'resources');
const runtime=path.join(resources,'runtime'),bundled=path.join(runtime,'browsers'),output=path.join(root,'build/test-results');
fs.mkdirSync(output,{recursive:true});
const report={target,testData:data,components:bundled,checks:[],errors:[]};
const env={...process.env,HTTP_PROXY:'http://127.0.0.1:9',HTTPS_PROXY:'http://127.0.0.1:9',ALL_PROXY:'http://127.0.0.1:9',NO_PROXY:'localhost,127.0.0.1',PAPERTRAIL_TEST_DATA_DIR:data,PAPERTRAIL_TEST_OFFLINE:'1'};
delete env.PAPERTRAIL_TEST_COMPONENTS_DIR;delete env.PLAYWRIGHT_BROWSERS_PATH;
const launch=()=>_electron.launch({executablePath:executable,args:[],env,timeout:60000});
let app;
(async()=>{
 assert.ok(componentsReady(path.join(runtime,'browser-module/playwright-core'),bundled));
 execFileSync(executable,[path.join(root,'scripts/smoke-browsers.cjs')],{env:{...env,ELECTRON_RUN_AS_NODE:'1',PAPERTRAIL_TEST_RUNTIME:runtime},timeout:90000,stdio:'inherit'});
 report.checks.push('Bundled Chromium and Firefox launch and render local content');
 app=await launch();let page=await app.firstWindow();
 page.on('pageerror',error=>report.errors.push(error.message));
 await page.getByRole('heading',{name:'投稿状态'}).waitFor({timeout:30000});
 assert.ok(page.url().startsWith('papertrail://app/'));
 assert.equal((await page.evaluate(()=>window.papertrail.info())).version,require('../package.json').version.replace(/\.0$/,''));
 await page.screenshot({path:path.join(output,'offline-'+target+'-welcome.png')});
 await page.getByRole('button',{name:'添加期刊账号',exact:true}).first().waitFor();
 assert.equal(fs.existsSync(path.join(data,'components')),false);
 report.checks.push('Fresh profile reaches the main UI without a download cache while download proxy is unreachable');
 await page.screenshot({path:path.join(output,'offline-'+target+'-overview.png')});
 await app.close();app=null;
 app=await launch();page=await app.firstWindow();
 await page.getByRole('heading',{name:'投稿状态'}).waitFor({timeout:30000});
 assert.equal(await page.getByRole('heading',{name:'欢迎使用 PaperTrail'}).count(),0);
 assert.equal(fs.existsSync(path.join(data,'components')),false);
 report.checks.push('Relaunch preserves the profile and reuses bundled components');
 assert.deepEqual(report.errors,[]);
 await app.close();app=null;report.ok=true;
})().catch(error=>{report.ok=false;report.error=error.stack;console.error(error);process.exitCode=1;}).finally(async()=>{
 if(app)await app.close().catch(()=>{});
 fs.writeFileSync(path.join(output,'first-launch-'+target+'.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
});
